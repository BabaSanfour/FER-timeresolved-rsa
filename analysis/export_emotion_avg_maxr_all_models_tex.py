"""Export emotion-averaged max-r for all models and EEG spatial scopes."""
import os
from pathlib import Path

import pandas as pd

ROOT = Path(os.environ.get("FER_ROOT", "."))
SCOPES = [
    "Ant-Left", "Ant-Right", "Post-Left", "Post-Right",
    "Temp-Left", "Temp-Right", "wholescalp", "ROI-avg",
]
HEADERS = [
    "Ant.-L", "Ant.-R", "Post.-L", "Post.-R",
    "Temp.-L", "Temp.-R", "Whole scalp", "ROI average",
]
STUDIES = {
    "18": ROOT / "analysis/paper_stats/timelocked_maxr_over_layers.csv",
    "54": ROOT / "analysis/paper_stats_54/timelocked_maxr_54.csv",
}


def escape(value):
    return str(value).replace("&", r"\&").replace("_", r"\_")


for study, source in STUDIES.items():
    df = pd.read_csv(source)
    df = df[df.emotion == "emo-avg"].copy()
    entities = (
        df[["model", "state"]].drop_duplicates()
        .sort_values(["model", "state"], key=lambda col: col.astype(str).str.lower())
    )

    lines = [
        "% Auto-generated by analysis/export_emotion_avg_maxr_all_models_tex.py",
        "% Requires: \\usepackage{booktabs}",
        r"\begin{table*}[htbp]",
        r"\centering",
        r"\small",
        rf"\caption{{Emotion-averaged maximum RSA correlations ($r_{{\max}}$) "
        rf"for all models and EEG spatial scopes in the {study}-stimulus analysis. "
        r"Emotion averages were calculated from the fear, happy, and neutral "
        r"condition-specific maximum correlations. ROI average is the mean of "
        r"the six ROI-specific $r_{\max}$ values.}",
        rf"\label{{tab:emotion-avg-maxr-{study}}}",
        r"\begin{tabular}{ll" + "r" * len(SCOPES) + "}",
        r"\toprule",
        "Model & Training & " + " & ".join(HEADERS) + r" \\",
        r"\midrule",
    ]
    previous_model = None
    for entity in entities.itertuples(index=False):
        q = df[(df.model == entity.model) & (df.state == entity.state)]
        values = []
        for scope in SCOPES:
            cell = q[q.roi == scope]
            values.append("--" if cell.empty else f"{float(cell.max_r.iloc[0]):.3f}")
        if previous_model is not None and entity.model != previous_model:
            lines.append(r"\addlinespace")
        lines.append(
            f"{escape(entity.model)} & {escape(entity.state)} & "
            + " & ".join(values) + r" \\"
        )
        previous_model = entity.model

    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    output = source.parent / f"emotion_avg_maxr_all_models_{study}.tex"
    output.write_text("\n".join(lines))
    print(f"[ok] {len(entities)} models -> {output}")

    # MathJax does not implement table/tabular/booktabs. Use a pure math array.
    mathjax = [
        rf"\[\text{{Emotion-averaged }} r_{{\max}}\text{{, {study} stimuli}}\]",
        r"\[",
        r"\begin{array}{ll" + "r" * len(SCOPES) + "}",
        r"\text{Model} & \text{Training} & "
        + " & ".join(rf"\text{{{header}}}" for header in HEADERS) + r" \\",
        r"\hline",
    ]
    previous_model = None
    for entity in entities.itertuples(index=False):
        q = df[(df.model == entity.model) & (df.state == entity.state)]
        values = []
        for scope in SCOPES:
            cell = q[q.roi == scope]
            values.append(r"\text{--}" if cell.empty else f"{float(cell.max_r.iloc[0]):.3f}")
        if previous_model is not None and entity.model != previous_model:
            mathjax.append(r"\hline")
        model_text = escape(entity.model)
        state_text = escape(entity.state)
        mathjax.append(
            rf"\text{{{model_text}}} & \text{{{state_text}}} & "
            + " & ".join(values) + r" \\"
        )
        previous_model = entity.model
    mathjax += [r"\end{array}", r"\]", ""]
    mathjax_output = source.parent / f"emotion_avg_maxr_all_models_{study}_mathjax.tex"
    mathjax_output.write_text("\n".join(mathjax))
    print(f"[ok] MathJax array -> {mathjax_output}")

    # OpenReview Markdown consumes one level of backslash escaping before MathJax.
    # Keep prose outside math mode and use only the supported l/r array preamble.
    openreview = [
        f"### Emotion-averaged maximum RSA correlations, {study} stimuli",
        "",
        "Values are averaged across fear, happy, and neutral. ROI average is the "
        "mean of the six ROI-specific maximum correlations.",
        "",
        "$$",
        r"\begin{array}{ll" + "r" * len(SCOPES) + "}",
        r"\text{Model} & \text{Training} & "
        + " & ".join(rf"\text{{{header}}}" for header in HEADERS) + r" \\",
        r"\hline",
    ]
    previous_model = None
    for entity in entities.itertuples(index=False):
        q = df[(df.model == entity.model) & (df.state == entity.state)]
        values = []
        for scope in SCOPES:
            cell = q[q.roi == scope]
            values.append(r"\text{--}" if cell.empty else f"{float(cell.max_r.iloc[0]):.3f}")
        if previous_model is not None and entity.model != previous_model:
            openreview.append(r"\hline")
        openreview.append(
            rf"\text{{{escape(entity.model)}}} & \text{{{escape(entity.state)}}} & "
            + " & ".join(values) + r" \\"
        )
        previous_model = entity.model
    openreview += [r"\end{array}", "$$", ""]
    # Required when pasting into an OpenReview field with Markdown enabled.
    openreview_escaped = "\n".join(openreview).replace("\\", "\\\\")
    openreview_output = source.parent / f"emotion_avg_maxr_all_models_{study}_openreview.md"
    openreview_output.write_text(openreview_escaped)
    print(f"[ok] OpenReview Markdown -> {openreview_output}")
